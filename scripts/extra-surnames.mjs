export function tokenizeYuan(text) {
  const compact = text.replace(/\s+/g, "");
  const names = [];
  for (let i = 0; i < compact.length; i += 1) {
    const two = compact.slice(i, i + 2);
    if (COMPOUNDS.includes(two)) {
      names.push(two);
      i += 1;
      continue;
    }
    names.push(compact[i]);
  }
  return names;
}

